<?php

namespace Gyro\Component\AttributeCollector;

use Composer\Composer;
use Composer\EventDispatcher\EventSubscriberInterface;
use Composer\IO\IOInterface;
use Composer\Plugin\PluginInterface;
use Composer\Script\Event;
use olvlvl\ComposerAttributeCollector\Config;

use function dirname;
use function file_exists;
use function file_put_contents;
use function is_dir;
use function mkdir;

use const DIRECTORY_SEPARATOR;

/**
 * Replaces the `post-autoload-dump` handler of olvlvl/composer-attribute-collector with one that
 * also scans the installed packages.
 *
 * Two wirings are supported, and the plugin behaves correctly under both:
 *
 * - upstream's plugin disabled through `config.allow-plugins`, so that the attributes file is
 *   generated exactly once — this is what Gyro itself does;
 * - both plugins enabled, in which case this handler runs last and its file wins.
 */
final class Plugin implements PluginInterface, EventSubscriberInterface
{
    /**
     * Runs after upstream's handler, which has no explicit priority and therefore sits at 0.
     */
    public const PRIORITY = -100;

    /**
     * @uses onPostAutoloadDump
     *
     * @codeCoverageIgnore
     */
    public static function getSubscribedEvents(): array
    {
        return [
            'post-autoload-dump' => [['onPostAutoloadDump', self::PRIORITY]],
        ];
    }

    /** @codeCoverageIgnore */
    public function activate(Composer $composer, IOInterface $io): void
    {
        self::writePlaceholder(
            Config::resolveVendorDir($composer) . DIRECTORY_SEPARATOR . Config::FILENAME,
        );
    }

    /** @codeCoverageIgnore */
    public function deactivate(Composer $composer, IOInterface $io): void
    {
    }

    /** @codeCoverageIgnore */
    public function uninstall(Composer $composer, IOInterface $io): void
    {
    }

    public static function onPostAutoloadDump(Event $event): void
    {
        Dumper::dump($event->getComposer(), $event->getIO());
    }

    /**
     * The attributes file is referenced from `autoload.files`, so it has to exist before the
     * autoloader is dumped — which happens before `post-autoload-dump` can generate the real thing.
     *
     * Upstream writes this placeholder in its own `activate()`, which does not run when its plugin
     * is disabled in favour of this one.
     */
    public static function writePlaceholder(string $filename): void
    {
        if (file_exists($filename)) {
            return;
        }

        $directory = dirname($filename);

        if (!is_dir($directory) && !mkdir($directory, 0o777, true) && !is_dir($directory)) {
            return;
        }

        $placeholder = <<<'PHP'
        <?php

        // attributes.php @generated by gyro/attribute-collector
        // This is a placeholder to enable the rendering of the autoloader.

        PHP;

        file_put_contents($filename, $placeholder);
    }
}
